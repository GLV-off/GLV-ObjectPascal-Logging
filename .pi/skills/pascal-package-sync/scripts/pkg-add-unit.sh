#!/usr/bin/env bash
# Module: pkg-add-unit.sh
# Author: <проект>
# Description: Добавляет юнит в <Files> пакета .lpk/.ctpkg с сохранением CRLF
#              и отступов; --check показывает diff и ничего не пишет.
# History: 2026-02-14: Created
#
# Usage: bash scripts/pkg-add-unit.sh <pkg.lpk|pkg.ctpkg> <unit.pas> [--check]
# Exit:  0 = добавлено/проверено; 2 = ошибка/отказ; 3 = юнит уже в пакете; 64 = аргументы.
# ВАЖНО: автоген-юнит пакета (*.pas рядом с .lpk) не правится — см. WARN.
set -uo pipefail

usage() {
  cat <<'EOF'
Usage: pkg-add-unit.sh <pkg.lpk|pkg.ctpkg> <unit.pas> [--check]
  --check  показать unified diff, файл пакета не менять
Exit: 0 ok, 2 ошибка/отказ, 3 юнит уже в пакете.
EOF
}
[ $# -ge 2 ] || { usage; exit 64; }
PKG="$1"; UF="$2"; CHECK=0
[ "${3:-}" = "--check" ] && CHECK=1
[ -f "$PKG" ] || { echo "RESULT|error|no-package|$PKG"; exit 2; }
[ -f "$UF" ]  || { echo "RESULT|error|no-unit|$UF"; exit 2; }
case "$PKG" in *.lpk|*.ctpkg) ;; *) echo "RESULT|error|bad-package-ext|$PKG"; exit 2;; esac
case "$UF" in *.pas) ;; *) echo "RESULT|error|bad-unit-ext|$UF"; exit 2;; esac

# автоген-юнит и сам пакет не правим
for f in "$PKG" "$UF"; do
  if head -1 "$f" | grep -q 'This file was automatically created'; then
    echo "RESULT|refuse|autogenerated|$f"; exit 2
  fi
done

unit_name="$(awk 'tolower($1)=="unit"{gsub(/;/,"",$2); print $2; exit}' "$UF")"
[ -n "$unit_name" ] || { echo "RESULT|error|no-unit-name|$UF"; exit 2; }
if grep -Fqi "<UnitName Value=\"$unit_name\"/>" "$PKG"; then
  echo "RESULT|skip|already-present|unit=$unit_name"; exit 3
fi

TMP="$(mktemp -d "${TMPDIR:-/tmp}/glv-add.XXXXXX" 2>/dev/null || mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
LF="$TMP/pkg.lf"; NEW="$TMP/pkg.new"; CAND="$TMP/pkg.cand"
tr -d '\r' <"$PKG" >"$LF"

# путь юнита относительно каталога пакета, в стиле пакета (обратные слэши)
pkgdir="$(dirname "$PKG")"
rel="$(realpath --relative-to="$pkgdir" "$UF" 2>/dev/null)" || {
  echo "RESULT|error|relative-path|$UF"; exit 2; }
relwin="$(printf '%s' "$rel" | awk '{gsub("/","\\"); print}')"

# отступ <Item> — как у первого существующего, иначе от <Files>
ind="$(sed -n 's/^\([[:space:]]*\)<Item>.*/\1/p' "$LF" | head -1)"
if [ -z "$ind" ]; then
  fi_ind="$(sed -n 's/^\([[:space:]]*\)<Files>.*/\1/p' "$LF" | head -1)"
  ind="${fi_ind:-    }  "
fi

# куда вставлять: перед <Item> первого юнита, который больше по имени, иначе перед </Files>
at="$(awk -v u="$unit_name" '
  /<Files>/ {inf=1; next}
  /<\/Files>/ {if(inf && !found){print NR}; inf=0; next}
  inf && /<Item>/ {item=NR}
  inf && /<UnitName Value="/ {
    split($0,a,"\""); v=a[2];
    if(!found && tolower(v) > tolower(u)){print item; found=1; exit}
  }' "$LF")"
[ -n "$at" ] || { echo "RESULT|error|no-files-section|$PKG"; exit 2; }

# блок вставки (LF; при необходимости потом станет CRLF)
RELWIN="$relwin" UNIT_NAME="$unit_name" awk -v ind="$ind" 'BEGIN{
  printf "%s<Item>\n%s  <Filename Value=\"%s\"/>\n%s  <UnitName Value=\"%s\"/>\n%s</Item>\n",
         ind, ind, ENVIRON["RELWIN"], ind, ENVIRON["UNIT_NAME"], ind
}' >"$TMP/block"

awk -v at="$at" -v bf="$TMP/block" '
  NR==at {while((getline l < bf) > 0) print l}
  {print}' "$LF" >"$NEW"

crlf=0
case "$(file -b "$PKG" 2>/dev/null)" in *CRLF*) crlf=1;; esac
if [ "$crlf" = 1 ]; then
  awk '{printf "%s\r\n", $0}' "$NEW" >"$CAND"
else
  cp "$NEW" "$CAND"
fi

if [ "$CHECK" = 0 ]; then
  cat "$CAND" >"$PKG"
  echo "RESULT|added|$PKG|unit=$unit_name|file=$relwin"
else
  diff -u --label "$PKG" --label "$PKG (new)" "$PKG" "$CAND" || true
  echo "RESULT|check|would-add|$PKG|unit=$unit_name|file=$relwin"
fi

gen="$pkgdir/$(basename "$PKG" ".${PKG##*.}").pas"
[ -f "$gen" ] && echo "WARN|autogen|$gen|не обновлён: пересоберите/установите пакет в IDE или добавьте юнит в автоген вручную"
exit 0
